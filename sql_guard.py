"""
Security validation module for SkillQuery SQL statements.
Enforces read-only access, limits, approved tables, and protects against SQL injection.
"""

import re

APPROVED_TABLES = {
    "ps_cleared_course_view",
    "ps_department_code_map",
    "ps_course_domain_map",
    "ps_student_course_summary"
}

FORBIDDEN_OPERATIONS = re.compile(
    r"\b(insert|update|delete|drop|alter|create|truncate|grant|revoke|"
    r"copy|call|execute|do|merge|refresh|vacuum|analyze|set|reset|"
    r"pg_sleep|information_schema|pg_catalog|pg_class|pg_shadow|pg_authid|pg_roles)\b",
    re.IGNORECASE
)

def validate_sql(sql: str) -> str:
    """
    Validates and sanitizes a raw SQL query generated by the LLM or user.
    Raises ValueError if query violates security boundaries.
    """
    if not sql or not isinstance(sql, str):
        raise ValueError("Empty or invalid query string.")

    cleaned = sql.strip()

    # 1. Strip markdown fences if present
    cleaned = re.sub(r"^```(?:sql)?\s*", "", cleaned, flags=re.IGNORECASE)
    cleaned = re.sub(r"\s*```$", "", cleaned)
    cleaned = cleaned.strip()

    # 2. Extract starting from SELECT or WITH
    match = re.search(r"^\s*(WITH\b.+?\bSELECT\b|SELECT\b).*", cleaned, re.IGNORECASE | re.DOTALL)
    if not match:
        raise ValueError("Only SELECT or WITH ... SELECT queries are permitted.")

    query = match.group(0).strip()

    # 3. Detect and prevent multi-statement injection (semicolons)
    # Strip any single trailing semicolon
    if query.endswith(";"):
        query = query[:-1].strip()

    # If there is another semicolon in the query, reject to prevent command chaining
    if ";" in query:
        raise ValueError("Multiple statements or chained SQL queries are forbidden.")

    # 4. Check for forbidden keywords / operations / system catalogs
    forbidden_match = FORBIDDEN_OPERATIONS.search(query)
    if forbidden_match:
        raise ValueError(f"Query contains forbidden operation or catalog: {forbidden_match.group(0)}")

    # 5. Check table allowlist: Must reference at least one approved table
    has_approved_table = any(
        re.search(r"\b" + re.escape(tbl) + r"\b", query, re.IGNORECASE)
        for tbl in APPROVED_TABLES
    )
    if not has_approved_table:
        raise ValueError(
            f"Query must reference one of the approved tables: {', '.join(sorted(APPROVED_TABLES))}"
        )

    # 6. Enforce safe LIMIT
    if not re.search(r"\blimit\s+\d+\b", query, re.IGNORECASE):
        query += " LIMIT 50"
    else:
        limit_match = re.search(r"\blimit\s+(\d+)\b", query, re.IGNORECASE)
        if limit_match and int(limit_match.group(1)) > 100:
            query = query[:limit_match.start(1)] + "100" + query[limit_match.end(1):]

    return query
